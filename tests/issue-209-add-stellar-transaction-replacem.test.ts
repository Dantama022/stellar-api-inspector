import { auditAddStellarTransactionReplacement209 } from '../src/services/issue-209-add-stellar-transaction-replacem';

describe('auditAddStellarTransactionReplacement209', () => {
  it('classifies normal, warning, and critical levels deterministically', () => {
    const normal = auditAddStellarTransactionReplacement209({
      targetId: 'G-TARGET-1',
      observedCount: 10,
      anomalyCount: 5,
      limitThreshold: 100,
    });
    expect(normal.level).toBe('normal');

    const warning = auditAddStellarTransactionReplacement209({
      targetId: 'G-TARGET-2',
      observedCount: 40,
      anomalyCount: 10,
    });
    expect(warning.level).toBe('warning');

    const critical = auditAddStellarTransactionReplacement209({
      targetId: 'G-TARGET-3',
      observedCount: 60,
      anomalyCount: 20,
      limitThreshold: 100,
    });
    expect(critical.level).toBe('critical');
  });

  it('rejects blank targetId', () => {
    expect(() =>
      auditAddStellarTransactionReplacement209({
        targetId: '   ',
        observedCount: 1,
        anomalyCount: 0,
      }),
    ).toThrow(/targetId is required/);
  });
});
