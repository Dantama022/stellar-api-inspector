import { auditAddStellarTransactionOperation205 } from '../src/services/issue-205-add-stellar-transaction-operatio';

describe('auditAddStellarTransactionOperation205', () => {
  it('classifies normal, warning, and critical levels deterministically', () => {
    const normal = auditAddStellarTransactionOperation205({
      targetId: 'G-TARGET-1',
      observedCount: 10,
      anomalyCount: 5,
      limitThreshold: 100,
    });
    expect(normal.level).toBe('normal');

    const warning = auditAddStellarTransactionOperation205({
      targetId: 'G-TARGET-2',
      observedCount: 40,
      anomalyCount: 10,
    });
    expect(warning.level).toBe('warning');

    const critical = auditAddStellarTransactionOperation205({
      targetId: 'G-TARGET-3',
      observedCount: 60,
      anomalyCount: 20,
      limitThreshold: 100,
    });
    expect(critical.level).toBe('critical');
  });

  it('rejects blank targetId', () => {
    expect(() =>
      auditAddStellarTransactionOperation205({
        targetId: '   ',
        observedCount: 1,
        anomalyCount: 0,
      }),
    ).toThrow(/targetId is required/);
  });
});
